export function getBlockWikiUrl(block: string): string {
  const id = normalizeBlockId(block);
  // Only arbitrary custom blocks need search; catalog coverage is checked by the audit.
  const path = Object.hasOwn(BLOCK_WIKI_PATHS, id) ? BLOCK_WIKI_PATHS[id]
    : `Special:Search?search=${encodeURIComponent(id.replaceAll("_", " "))}&go=Go`;
  return `https://minecraft.wiki/w/${path}`;
}
