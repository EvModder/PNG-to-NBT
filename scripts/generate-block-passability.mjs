#!/usr/bin/env bun
/**
 * Writes website/src/data/blockPassability.ts from a vanilla support probe, so passability
 * follows the target version instead of a hand-kept list. Run it after probing a new target
 * (see website/tests/README.md), review the printed changes, then refresh the support review.
 *
 * Public API:
 * - none
 */
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.join(ROOT, "website/src/data/blockPassability.ts");
const WIDTH = 118;

const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== "--input")) throw new Error("Usage: generate-block-passability.mjs [--input probe.json]");
const input = args[1] ?? path.join(ROOT, "work_files/reports/block-support/probe.json");
const probe = JSON.parse(await fs.readFile(input, "utf8"));
if (probe.schema !== 3) throw new Error("Expected a schema 3 probe from scripts/BlockSupportProbe.java");

const parse = entry => new Map([...entry.matchAll(/(\w+)=([^,\]]+)/g)].map(([, key, value]) => [key, value]));
const always = [];
const conditional = new Map();
for (const [id, block] of Object.entries(probe.blocks)) {
  const states = Object.entries(block.states).map(([entry, facts]) => ({ props: parse(entry), passable: facts.passable }));
  const passable = states.filter(state => state.passable);
  if (passable.length === states.length) always.push(id);
  if (!passable.length || passable.length === states.length) continue;
  // The property values shared by every passable state must also select exactly those states.
  const when = [...passable[0].props].filter(([key, value]) => passable.every(state => state.props.get(key) === value));
  if (!states.every(state => when.every(([key, value]) => state.props.get(key) === value) === state.passable)) {
    throw new Error(`No property values select the passable states of ${id}; extend the data format`);
  }
  // Missing properties in a block entry take the vanilla default.
  const defaults = parse(block.default);
  const key = JSON.stringify(Object.fromEntries(when.map(([name, value]) => [name, [value, defaults.get(name)]])));
  if (!conditional.has(key)) conditional.set(key, []);
  conditional.get(key).push(id);
}

const list = (items, indent) => {
  const lines = [];
  let line = indent;
  for (const item of items) {
    const next = `${JSON.stringify(item)},`;
    if (line.length + next.length + 1 > WIDTH && line.trim()) {
      lines.push(line.trimEnd());
      line = indent;
    }
    line += `${next} `;
  }
  return [...lines, line.trimEnd()].join("\n");
};
const conditions = [...conditional].map(([when, ids]) => {
  const entries = Object.entries(JSON.parse(when)).map(([name, [value, fallback]]) => `${name}: ["${value}", "${fallback}"]`);
  return `  [[\n${list(ids.sort(), "    ")}\n  ], { ${entries.join(", ")} }],`;
});
const source = `/**
 * Generated by scripts/generate-block-passability.mjs from vanilla ${probe.version} (data version ${probe.dataVersion}).
 * Do not edit manually. Blocks without a collision box, so entities move through them.
 *
 * Public API:
 * - PASSABLE_BLOCKS
 * - PASSABLE_WHEN
 *
 * Callers:
 * - src/lib/blockSupport.ts
 */

// Callers:
// - src/lib/blockSupport.ts
// Passable in every state.
export const PASSABLE_BLOCKS: ReadonlySet<string> = new Set([
${list(always.sort(), "  ")}
]);

// Callers:
// - src/lib/blockSupport.ts
// Passable only in these property values. Each property maps to [passable value, default value].
export const PASSABLE_WHEN: readonly (readonly [readonly string[], Readonly<Record<string, readonly [string, string]>>])[] = [
${conditions.join("\n")}
];
`;

// Report version changes, so they can be reviewed like other support facts.
const previous = await import(pathToFileURL(OUTPUT).href).catch(() => null);
if (previous) {
  const before = new Set(previous.PASSABLE_BLOCKS);
  const added = always.filter(id => !before.has(id)), removed = [...before].filter(id => !always.includes(id));
  const describe = rows => new Map(rows.flatMap(([ids, when]) => ids.map(id => [id, JSON.stringify(when)])));
  const oldWhen = describe(previous.PASSABLE_WHEN), newWhen = describe([...conditional].map(([when, ids]) => [ids, JSON.parse(when)]));
  const changed = [...new Set([...oldWhen.keys(), ...newWhen.keys()])].filter(id => oldWhen.get(id) !== newWhen.get(id));
  console.log(`Always passable: +${added.length} -${removed.length}${added.length ? ` added ${added.join(", ")}` : ""}${removed.length ? ` removed ${removed.join(", ")}` : ""}`);
  console.log(`State-dependent: ${changed.length ? `changed ${changed.join(", ")}` : "unchanged"}`);
}
await fs.writeFile(OUTPUT, source);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)}: ${always.length} always passable, ${[...conditional.values()].flat().length} by state`);
